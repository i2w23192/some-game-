// Resolve a sprite name to rows of palette keys.
export function resolveSprite(name) {
  const def = SPRITES[name];
  if (!def) throw new Error(`Unknown sprite ${name}`);
  if (Array.isArray(def)) return def;
  const base = T[def.base] || resolveSprite(def.base);
  const map = def.map;
  return base.map((row) => {
    let out = '';
    for (const ch of row) out += map[ch] !== undefined ? map[ch] : ch;
    return out;
  });
}
