// Regenerates sw-assets.js: the list of files the service worker pre-caches,
// plus a content hash so installed copies update when anything changes.
//   node tools/update-sw.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const include = ['index.html', 'style.css', 'manifest.webmanifest', 'src', 'assets'];
const files = [];
const walk = (p) => {
  if (statSync(p).isDirectory()) { for (const f of readdirSync(p).sort()) walk(join(p, f)); return; }
  const rel = relative(root, p);
  if (rel.startsWith('src/dev/') && rel !== 'src/dev/bot.js') return;
  if (/\.(txt|md)$/.test(rel)) return;
  files.push(rel);
};
for (const i of include) walk(join(root, i));
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(root, f)));
const version = hash.digest('hex').slice(0, 12);
const list = ['./', ...files];
writeFileSync(join(root, 'sw-assets.js'),
  `// Generated by tools/update-sw.mjs. Do not edit by hand.\nself.ASSET_VERSION = '${version}';\nself.ASSETS = ${JSON.stringify(list, null, 2)};\n`);
console.log(`sw-assets.js: ${list.length} files, version ${version}`);
